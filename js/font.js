// Cyrillic letters that look like Latin ones share their glyphs; Ё is drawn as Е
const GLYPH_ALIAS = { 'А': 'A', 'В': 'B', 'Е': 'E', 'Ё': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X' };
const glyphRows = ch => GLYPHS[ch] || GLYPHS[GLYPH_ALIAS[ch]];

const glyphCache = new Map();
function glyph(ch, color) {
  const key = color + ch;
  let c = glyphCache.get(key);
  if (!c) {
    c = document.createElement('canvas');
    c.width = 8; c.height = 8;
    const g = c.getContext('2d'), rows = glyphRows(ch);
    g.fillStyle = color;
    if (rows) rows.forEach((row, y) => { for (let x = 0; x < row.length; x++) if (row[x] === '#') g.fillRect(x, y, 1, 1); });
    glyphCache.set(key, c);
  }
  return c;
}

/** Draw text with the 8-px font; returns the width drawn. */
function drawText(g, text, x, y, color) {
  const s = String(text).toUpperCase();
  for (let i = 0; i < s.length; i++) if (s[i] !== ' ') g.drawImage(glyph(s[i], color), Math.round(x) + i * 8, Math.round(y));
  return s.length * 8;
}

function drawTextCentered(g, text, cx, y, color) {
  drawText(g, text, cx - String(text).length * 4, y, color);
}

/** Word-wrap to lines of at most `max` characters; '\n' forces a break. */
function wrapText(text, max) {
  const lines = [];
  for (const para of String(text).split('\n')) {
    let cur = '';
    for (const w of para.split(/\s+/).filter(Boolean)) {
      if (!cur) cur = w;
      else if ((cur + ' ' + w).length <= max) cur += ' ' + w;
      else { lines.push(cur); cur = w; }
    }
    lines.push(cur);
  }
  return lines;
}
